PLANT_ARTS: dict[str, dict[GrowthStage, dict[HealthState, list[str]]]] = {
    "juniper": JUNIPER_ART,
    "sakura": SAKURA_ART,
    "maple": MAPLE_ART,
    "pine": PINE_ART,
}


def get_plant_art(type_id: str, growth_stage: GrowthStage, health_state: HealthState) -> list[str]:
    """Retrieve corresponding 29x13 art matrix for species, stage, and health state."""
    art_dict = PLANT_ARTS.get(type_id, JUNIPER_ART)
    stage_dict = art_dict.get(growth_stage, art_dict[GrowthStage.SEED])
    return stage_dict.get(health_state, EMPTY_POT)

