"""Organic ASCII art matrices for bonsai trees in a ceramic pot.
All arts are strictly 29 columns wide and 13 lines high.
"""
from vimgarden.enums import GrowthStage, HealthState

POT_BASE: list[str] = [
    "  [=======================]  ",
    "   \\                     /   ",
    "    \\__===_________===__/    ",
]

EMPTY_POT: list[str] = [
    "                             ",
    "                             ",
    "                             ",
    "                             ",
    "                             ",
    "                             ",
    "                             ",
    "                             ",
    "                             ",
    "    . ~ . ~ . ~ . ~ . ~ .    ",
] + POT_BASE


def _pad_art(lines: list[str]) -> list[str]:
    """Ensure all lines are strictly 29 characters wide."""
    result = []
    for line in lines:
        if len(line) < 29:
            line = line.ljust(29)
        elif len(line) > 29:
            line = line[:29]
        result.append(line)
    return result


